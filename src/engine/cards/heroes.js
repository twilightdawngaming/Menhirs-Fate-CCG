import { mk } from './schema.js';

// ---------------------------------------------------------------------------
// HEROES OF ELANDRA
// ---------------------------------------------------------------------------
// Combat model (MTG-lite):
//   Might   — damage dealt and damage survived
//   Vigil   — how many heroes by which you may be attacked (your line)
//   Guardian — foes must block it; may block Soaring
//   Swift    — no arrival sickness;  Soaring — must be blocked by Soaring/Anchor
//   Duelist  — strikes first;  Overrun — excess damage hits the foe's Resolve
//   Drain    — damage dealt restores your Resolve
// ---------------------------------------------------------------------------

const H = (id, n, nation, sp, cost, might, vigil, kw, txt, ab, fl, rarity) => mk({
  id, n, nation, sp, cost, type: 'hero', might, vigil, kw: kw || [],
  txt: txt || '', ab: ab || [], fl: fl || '', rarity: rarity || 'common',
});

