import { mk } from './schema.js';

// ---------------------------------------------------------------------------
// CANTRIPS  — the small quick magics. Playable on your Main and in response
//             during a Clash (there is a response window after every attack).
// RITES     — the long, slow, deliberate workings. Main phase only.
// WEAVEMARKS— auras that attach to a hero.
// RELICS    — forged objects that persist.  Menhirs are the relics that enable
//             Weavings (the big narrative rituals).
// ---------------------------------------------------------------------------

const C = (id, n, nation, sp, cost, txt, ab, fl, rarity) => mk({
  id, n, nation, sp, cost, type: 'cantrip', kind: 'Cantrip', txt, ab, fl, rarity: rarity || 'common',
});
const R = (id, n, nation, sp, cost, txt, ab, fl, rarity) => mk({
  id, n, nation, sp, cost, type: 'rite', kind: 'Rite', txt, ab, fl, rarity: rarity || 'common',
});
const W = (id, n, nation, sp, cost, txt, ab, fl, rarity) => mk({
  id, n, nation, sp, cost, type: 'weavemark', kind: 'Weavemark', txt, ab, fl, rarity: rarity || 'uncommon',
});
const Rl = (id, n, nation, sp, cost, txt, ab, fl, rarity) => mk({
  id, n, nation, sp, cost, type: 'relic', kind: 'Relic', txt, ab, fl, rarity: rarity || 'uncommon',
});

