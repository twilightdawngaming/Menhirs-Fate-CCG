// ---------------------------------------------------------------------------
// tools/build-static.mjs — produce a self-contained static site in ./dist
//
//   node tools/build-static.mjs
//   WS_URL=wss://duels.example.com/ws node tools/build-static.mjs
//
// The campaign and AI duels run entirely in the browser, so a static host is
// enough for single-player. Point WS_URL at a running game server (npm start)
// if you also want room-code duels; leave it empty to disable them.
// ---------------------------------------------------------------------------
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const DIST = path.join(ROOT, 'site');
const wsUrl = process.env.WS_URL || '';

const rm = (p) => fs.rmSync(p, { recursive: true, force: true });
const copyDir = (from, to) => {
  fs.mkdirSync(to, { recursive: true });
  for (const entry of fs.readdirSync(from, { withFileTypes: true })) {
    const src = path.join(from, entry.name);
    const dst = path.join(to, entry.name);
    if (entry.isDirectory()) copyDir(src, dst);
    else fs.copyFileSync(src, dst);
  }
};
const walk = (dir, out = []) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
};
const bytes = (p) => walk(p).reduce((a, f) => a + fs.statSync(f).size, 0);
const kb = (n) => `${(n / 1024).toFixed(0)} KB`;

// 1. start clean and copy the client plus the shared engine
rm(DIST);
copyDir(path.join(ROOT, 'public'), DIST);
copyDir(path.join(ROOT, 'src'), path.join(DIST, 'src'));

// 2. rewrite the browser-style absolute imports (/src/...) so the site works
//    at a domain root *or* under a sub-path such as /menhirs-fate/
let rewritten = 0;
for (const file of walk(path.join(DIST, 'js'))) {
  if (!file.endsWith('.js')) continue;
  const before = fs.readFileSync(file, 'utf8');
  const after = before.replace(/(['"])\/src\//g, '$1../src/');
  if (after !== before) { fs.writeFileSync(file, after); rewritten++; }
}

// 3. write the runtime config for this deployment
fs.writeFileSync(path.join(DIST, 'config.js'),
`// generated by tools/build-static.mjs
window.MF_CONFIG = { wsUrl: ${JSON.stringify(wsUrl)} };
`);

// 4. GitHub Pages: stop Jekyll from touching anything
fs.writeFileSync(path.join(DIST, '.nojekyll'), '');

// 5. a friendly fallback page for unknown paths
fs.writeFileSync(path.join(DIST, '404.html'),
  `<!DOCTYPE html><meta charset="utf-8"><title>Menhirs Fate</title>
<body style="margin:0;font:15px/1.6 system-ui,sans-serif;color:#e8dfc8;background:#0b1210;display:grid;place-items:center;height:100vh">
<div style="text-align:center">
  <h1 style="font-family:Georgia,serif;letter-spacing:.05em">Menhirs Fate</h1>
  <p>The mist took that page.</p>
  <p><a style="color:#c9a44c" href="./">Return to Haven</a></p>
</div></body>`);

console.log(`static build written to site/  (${kb(bytes(DIST))})`);
console.log(`  engine modules rewritten: ${rewritten} client file(s) now use relative paths`);
console.log(`  duel server: ${wsUrl || 'none configured — online duels disabled, single-player works'}`);
console.log('  preview locally:  npm run serve:dist     (or any static host)');
